"""Independent computational checks for the Hexagon candidate H22 (the adjoined-zero semiring G(R) = R ⊔ {τ}).
By the main session (Claude Opus 5.5 at effort max), 21 Nov 2026. Pure Python, exact, finite rings Z/n and F_p.
1. G(Z/n) is a commutative semiring; its prime ideals are {τ} and P ∪ {τ}; {τ} is the unique minimal prime.
2. Product theorem: G(Z/6) ≅ G(Z/2) ×_B G(Z/3) (fibre product over the support characters).
3. Free semimodules G(F_p)^n: skeleton e·M = support patterns (Boolean cube), fibre over I = F_p^I.
4. Classification on semimodules NOT built from diagrams: random subsemimodules M of G(F_p)^n generated by random
   vectors; decompose M by ε(m) = e·m; check that fibres are F_p-vector spaces with zero element the idempotent l,
   that transports T(m) = m + l' are F_p-linear and functorial, and that addition is recovered as
   m + n = T(m) + T(n) inside the fibre over the join, i.e. M ≅ M(diagram of M)."""
import itertools, random, sys
sys.stdout.reconfigure(encoding="utf-8")
T = "t"  # tau


def G_ops(n):
    def add(x, y):
        if x == T: return y
        if y == T: return x
        return (x + y) % n
    def mul(x, y):
        if x == T or y == T: return T
        return (x * y) % n
    return [T] + list(range(n)), add, mul


def check_semiring(n):
    E, add, mul = G_ops(n)
    for a, b, c in itertools.product(E, repeat=3):
        assert add(add(a, b), c) == add(a, add(b, c)) and mul(mul(a, b), c) == mul(a, mul(b, c))
        assert mul(a, add(b, c)) == add(mul(a, b), mul(a, c))
    for a in E:
        assert add(T, a) == a and mul(T, a) == T and mul(1, a) == a
    # ideals and primes
    ideals = []
    for r in range(len(E) + 1):
        for I in itertools.combinations(E, r):
            I = set(I)
            if T not in I: continue
            if all(add(x, y) in I for x in I for y in I) and all(mul(s, x) in I for s in E for x in I):
                ideals.append(frozenset(I))
    primes = [I for I in ideals if I != set(E) and all(mul(x, y) not in I or x in I or y in I for x in E for y in E)]
    assert frozenset({T}) in primes and all(frozenset({T}) <= P for P in primes)
    ring_primes = [p for p in range(2, n + 1) if n % p == 0 and all(p % q for q in range(2, p))]
    expected = {frozenset({T})} | {frozenset({T} | {x for x in range(n) if x % p == 0}) for p in ring_primes}
    if n in (2, 3, 5, 7):  # a field: its zero ideal is prime too
        expected.add(frozenset({T, 0}))
    assert set(primes) == expected, (n, primes, expected)
    return len(ideals), len(primes)


def check_product():
    E6, a6, m6 = G_ops(6); E2, a2, m2 = G_ops(2); E3, a3, m3 = G_ops(3)
    chi = lambda x: 0 if x == T else 1
    fib = [(x, y) for x in E2 for y in E3 if chi(x) == chi(y)]
    phi = {T: (T, T)}
    for k in range(6): phi[k] = (k % 2, k % 3)  # CRT on the supported part
    assert sorted(phi.values(), key=str) == sorted(fib, key=str)
    for x, y in itertools.product(E6, repeat=2):
        assert phi[a6(x, y)] == (a2(phi[x][0], phi[y][0]), a3(phi[x][1], phi[y][1]))
        assert phi[m6(x, y)] == (m2(phi[x][0], phi[y][0]), m3(phi[x][1], phi[y][1]))
    return len(fib)


def vadd(p):
    E, add, mul = G_ops(p)
    return (lambda u, v: tuple(add(a, b) for a, b in zip(u, v)), lambda r, v: tuple(mul(r, a) for a in v), E)


def closure(gens, p):
    add, smul, E = vadd(p)
    n = len(gens[0]); zero = tuple([T] * n)
    M = {zero} | set(gens)
    changed = True
    while changed:
        changed = False
        cur = list(M)
        for u in cur:
            for r in E:
                w = smul(r, u)
                if w not in M: M.add(w); changed = True
        for u, v in itertools.product(cur, repeat=2):
            w = add(u, v)
            if w not in M: M.add(w); changed = True
    return M


def check_classification(p, n, k, seed):
    rnd = random.Random(seed)
    E = [T] + list(range(p))
    gens = [tuple(rnd.choice(E) for _ in range(n)) for _ in range(k)]
    M = closure(gens, p)
    add, smul, _ = vadd(p)
    e = 0  # the supported zero 0_R
    eps = {m: smul(e, m) for m in M}
    L = set(eps.values())
    for l in L:  # skeleton elements are idempotent and form a join-semilattice under +
        assert add(l, l) == l
        for l2 in L: assert add(l, l2) in L
    fibres = {l: [m for m in M if eps[m] == l] for l in L}
    for l, F in fibres.items():
        assert l in F  # the fibre's zero element is l itself
        for u in F:
            assert add(u, l) == u and add(u, smul(p - 1, u)) == l  # additive inverse inside the fibre
            for v in F: assert eps[add(u, v)] == l
        size = len(F)
        assert size & (size - 1) == 0 or round(size ** (1 / max(1, round(__import__('math').log(size, p))))) == p or size == 1
    order = lambda a, b: add(a, b) == b  # a <= b in L
    for l, l2 in itertools.product(L, repeat=2):
        if not order(l, l2): continue
        Tm = {u: add(u, l2) for u in fibres[l]}
        assert all(eps[w] == l2 for w in Tm.values())
        for u, v in itertools.product(fibres[l], repeat=2):  # transport is additive
            assert Tm[add(u, v)] == add(Tm[u], Tm[v])
        for r in range(p):
            for u in fibres[l]: assert Tm[smul(r, u)] == smul(r, Tm[u])
        for l3 in L:  # functoriality
            if order(l2, l3):
                for u in fibres[l]: assert add(Tm[u], l3) == add(u, l3)
    for u, v in itertools.product(M, repeat=2):  # addition recovered through the join
        j = add(eps[u], eps[v])
        assert add(add(u, j), add(v, j)) == add(u, v)
    return len(M), len(L)


def check_retract_lemma(n):
    """Every idempotent join-endomorphism e of P([n]) (e(S) = union of E_k, k in S, with e∘e = e) has a distributive
    image lattice; and every order-ideal lattice Idl(J) of a poset on [n] is such an image (down-closure)."""
    X = range(n)
    count = 0
    for bits in range(1 << (n * n)):
        E = [frozenset(m for m in X if bits >> (k * n + m) & 1) for k in X]
        e = lambda S: frozenset().union(*[E[k] for k in S]) if S else frozenset()
        if any(e(E[k]) != E[k] for k in X):
            continue  # not idempotent
        count += 1
        img = {e(frozenset(S)) for r in range(n + 1) for S in itertools.combinations(X, r)}
        meet = lambda U, V: e(U & V)  # the meet in the image
        for U, V, W in itertools.product(img, repeat=3):
            assert meet(U, V | W) == meet(U, V) | meet(U, W)  # distributive
    return count


